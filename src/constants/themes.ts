/**
 * Migration & Deterministic Mapping:
 * Maps old mood-based theme IDs to the new 13 Color Families
 */
export function migrateThemeId(legacyId?: string): { familyId: ColorFamilyId; mode: AppearanceMode } {
  switch (legacyId) {
    case 'midnight':
      return { familyId: 'black', mode: 'dark' };
    case 'dreamy':
      return { familyId: 'pink', mode: 'light' };
    case 'sunlit':
      return { familyId: 'yellow', mode: 'light' };
    case 'quiet':
      return { familyId: 'white', mode: 'light' };
    case 'nature':
      return { familyId: 'green', mode: 'light' };
    case 'playful':
      return { familyId: 'purple', mode: 'dark' };
    case 'red':
    case 'blue':
    case 'yellow':
    case 'green':
    case 'orange':
    case 'purple':
    case 'pink':
    case 'brown':
    case 'black':
    case 'white':
    case 'gray':
    case 'silver':
    case 'gold':
      return { familyId: legacyId as ColorFamilyId, mode: 'light' };
    default:
      return { familyId: 'brown', mode: 'light' };
  }
}

/**
 * Deterministic Mood-to-Theme Mapping for "Follow Story" mode
 */
export function mapMoodToColorFamily(mood: MoodType): { familyId: ColorFamilyId; mode: AppearanceMode } {
  switch (mood) {
    case 'melancholy':
      return { familyId: 'blue', mode: 'dark' };
    case 'nostalgic':
      return { familyId: 'brown', mode: 'light' };
    case 'peaceful':
      return { familyId: 'green', mode: 'light' };
    case 'happy':
      return { familyId: 'yellow', mode: 'light' };
    case 'thoughtful':
      return { familyId: 'silver', mode: 'light' };
    case 'playful':
      return { familyId: 'purple', mode: 'dark' };
    default:
      return { familyId: 'brown', mode: 'light' };
  }
}

/**
 * Helper to construct ThemeConfig object from family + appearance mode
 */
export function buildThemeConfig(familyId: ColorFamilyId, mode: AppearanceMode): ThemeConfig {
  const family = THEME_FAMILIES[familyId] || THEME_FAMILIES.brown;
  const tokens = family.variants[mode] || family.variants.light;

  return {
    id: family.id,
    familyId: family.id,
    name: `${family.name} (${mode === 'dark' ? 'Dark' : 'Light'})`,
    nameTh: `${family.nameTh} (${mode === 'dark' ? 'โหมดมืด' : 'โหมดสว่าง'})`,
    description: family.descriptionEn,
    mode,
    tokens,
    bgHex: tokens.pageBg,
    bgClass: 'theme-page-bg',
    cardBgClass: 'theme-surface',
    textClass: 'theme-text-primary',
    mutedTextClass: 'theme-text-muted',
    borderClass: 'theme-border',
    accentHex: tokens.accent,
    accentClass: 'theme-accent',
  };
}

